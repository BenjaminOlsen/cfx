static void test_quarter_round(void) {
    uint32_t a = 0x11111111, b = 0x01020304, c = 0x9b8d6f43, d = 0x01234567;
    QR(a, b, c, d);
    CFX_ASSERT(a == 0xea2a92f4);
    CFX_ASSERT(b == 0xcb1cf8ce);
    CFX_ASSERT(c == 0x4581472e);
    CFX_ASSERT(d == 0x5881c4bb);
}

